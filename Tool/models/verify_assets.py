"""资产验收：两个 .glb 能否被 Godot 4.7 直接导入，且 AABB / 原点 / 朝向与仿真参数一致。

四段，每段独立定位失败点：

  [0/4] 只读快照：git status 基线 + src/ 树摘要 + project.godot / COMPONENTS.md 的 sha256
  [1/4] /tmp 最小工程：写 project.godot(config_version=5) → 拷 .glb + check_tree.gd/.tscn
        → godot --headless --import → 跑 CheckTree 主场景 → 解析 [ASSET]/[ASSERT]/[RESULT]
  [2/4] 真实工程：godot --headless --path orion-simulation-world --import
        → 确认 assets/*.glb.import；清理本次新生成的 src/**/*.gd.uid；复核 src 树摘要未变
  [3/4] assets/ 白名单：恰好 6 个文件、无 .blend、.glb 非空
  [4/4] git status delta：只允许 assets/ 的 .glb/.glb.import 与 Tool/models/（只读，不 add/commit）

全部通过 exit 0；有失败 exit 1 并打印差异；Godot 缺失 exit 2。

用法：
    python3 Tool/models/verify_assets.py [--keep-tmp] [--godot /path/to/godot]

期望值出处（1 BU = 1 m，Godot Y-up，前进 = 局部 +X）：
    UGV 轮半径 0.06                     orion-simulation-world/src/chassis/DiffDrive.gd:33
        wheel_base / track_width / height = 0.30 / 0.24 / 0.16   DiffDrive.gd:41-43
        轮心 x=±0.15, z=∓0.12            DiffDrive.gd:159-161
        → Body 包络 (0.30, 0.16, 0.24)；整机 (0.42, 0.16, 0.28)
          （整机 X 含轮子前后外伸 2×0.06；step.md 字面的 "X=0.30" 是车身/碰撞盒口径）
    UAV size 0.40 / BODY_HEIGHT 0.12 / ROTOR_LIFT 0.01 / 旋翼半径 0.12 厚 0.02
        Quadrotor.gd:68,50,52 + src/scenes/chassis/Quadrotor.tscn:17-20
        → 整机 (0.64, 0.14, 0.64)
"""

