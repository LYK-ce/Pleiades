PROBLEMS: list[str] = []
SECTIONS: list[tuple[str, bool]] = []
KEY_NUMBERS: dict[str, str] = {}


# ── 小工具 ────────────────────────────────────────────────────────────────────


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def tree_files(root: Path) -> dict[str, str]:
    return {
        p.relative_to(root).as_posix(): sha256_file(p)
        for p in sorted(root.rglob("*"))
        if p.is_file()
    }


def tree_digest(files: dict[str, str]) -> str:
    blob = "\n".join(f"{k} {v}" for k, v in sorted(files.items()))
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def problem(message: str) -> None:
    PROBLEMS.append(message)
    print(f"      !! {message}")


def git_status() -> set[str]:
    proc = subprocess.run(
        ["git", "status", "--porcelain", "-uall"],
        cwd=PROJECT_ROOT,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        problem(f"git status 失败 rc={proc.returncode}: {proc.stderr.strip()}")
        return set()
    return {line for line in proc.stdout.splitlines() if line.strip()}


def _as_text(value) -> str:
    if value is None:
        return ""
    return value.decode("utf-8", "replace") if isinstance(value, bytes) else value


def run(argv: list[str], timeout: int = 300) -> subprocess.CompletedProcess:
    print("      $ " + " ".join(str(a) for a in argv))
    started = time.time()
    try:
        proc = subprocess.run(argv, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired as exc:
        print(f"      !! 超时 {timeout}s（进程已 kill）")
        return subprocess.CompletedProcess(
            argv, -1, _as_text(exc.stdout), _as_text(exc.stderr)
        )
    print(f"      rc={proc.returncode}  ({time.time() - started:.1f}s)")
    return proc


def dump_output(proc: subprocess.CompletedProcess, limit: int = 60) -> None:
    for name, text in (("stdout", proc.stdout), ("stderr", proc.stderr)):
        lines = (text or "").rstrip().splitlines()
        if not lines:
            continue
        print(f"      --- {name} ({len(lines)} lines) ---")
        for line in lines[:limit]:
            print("      | " + line)
        if len(lines) > limit:
            print(f"      | ... ({len(lines) - limit} more lines)")


# ── 段 0：只读快照 ────────────────────────────────────────────────────────────


def segment0() -> dict:
    print(f"[0/4] baseline  git status entries=...  ", end="")
    baseline = git_status()
    src_root = WORLD / "src"
    src_before = tree_files(src_root) if src_root.is_dir() else {}
    src_sha = tree_digest(src_before)

    watch = {}
    for rel in ("project.godot", "COMPONENTS.md"):
        path = WORLD / rel
        watch[rel] = sha256_file(path) if path.is_file() else "<missing>"

    print(f"entries={len(baseline)}  src_files={len(src_before)}  src_tree_sha={src_sha[:8]}…")
    for rel, digest in watch.items():
        print(f"      {rel:16s} sha={digest[:16]}…")
    return {
        "git": baseline,
        "src_files": src_before,
        "src_sha": src_sha,
        "watch": watch,
    }


# ── 段 1：/tmp 最小工程导入 + CheckTree ───────────────────────────────────────


def parse_check_tree(stdout: str) -> None:
    asset_re = re.compile(
        r"\[ASSET\]\s+(\S+)\s+objects=(\d+)\s+tris=(\d+)\s+"
        r"min=\(([-\d.]+),([-\d.]+),([-\d.]+)\)\s+max=\(([-\d.]+),([-\d.]+),([-\d.]+)\)\s+"
        r"size=\(([-\d.]+),([-\d.]+),([-\d.]+)\)"
    )
    nose_re = re.compile(r"\[NOSE\]\s+(\S+)\s+surfaces=(\d+)\s+center_x=(n/a|[-\d.]+)")
    spec_re = re.compile(r"\[SPEC\]\s+(.+)")

    seen = {}
    for match in asset_re.finditer(stdout):
        seen[match.group(1)] = {
            "objects": int(match.group(2)),
            "tris": int(match.group(3)),
            "size": tuple(float(match.group(i)) for i in (10, 11, 12)),
        }
        print(
            f"      parsed {match.group(1)}: objects={match.group(2)} tris={match.group(3)} "
            f"size=({match.group(10)},{match.group(11)},{match.group(12)})"
        )

    noses = {}
    for match in nose_re.finditer(stdout):
        raw = match.group(3)
        noses[match.group(1)] = {
            "surfaces": int(match.group(2)),
            "center_x": None if raw == "n/a" else float(raw),
        }
        print(f"      parsed {match.group(1)}: nose_surfaces={match.group(2)} center_x={raw}")

    for match in spec_re.finditer(stdout):
        print(f"      {match.group(0)}")

    for name, expect in EXPECTED.items():
        got = seen.get(name)
        if got is None:
            problem(f"CheckTree 未打印 {name} 的 [ASSET] 行")
            continue
        if got["objects"] != expect["objects"]:
            problem(f"{name} objects: CheckTree={got['objects']} 独立核对={expect['objects']}")
        if got["tris"] != expect["tris"]:
            problem(f"{name} tris: CheckTree={got['tris']} 独立核对={expect['tris']}")
        for axis, index in (("X", 0), ("Y", 1), ("Z", 2)):
            if abs(got["size"][index] - expect["size"][index]) > 0.01:
                problem(
                    f"{name} size.{axis}: CheckTree={got['size'][index]:.6f} "
                    f"独立核对={expect['size'][index]:.6f}"
                )
        nose = noses.get(name)
        if nose is None or nose["surfaces"] < 1 or nose["center_x"] is None:
            problem(f"{name} 未解析到红面中心 x（朝向无法二次核对）")
        elif nose["center_x"] <= expect["nose_gt"]:
            problem(
                f"{name} nose center_x={nose['center_x']:.6f} 未超过独立下限 {expect['nose_gt']:.3f}"
            )
        else:
            KEY_NUMBERS[f"{name}/nose_x"] = f"{nose['center_x']:.6f}"
        KEY_NUMBERS[f"{name}/size"] = "({:.4f}, {:.4f}, {:.4f})".format(*got["size"])
        KEY_NUMBERS[f"{name}/objects_tris"] = f"{got['objects']} / {got['tris']}"

    if "[RESULT] PASS" not in stdout:
        problem("CheckTree 未输出 [RESULT] PASS")


def segment1(keep_tmp: bool) -> bool:
    tmpdir = Path(tempfile.mkdtemp(prefix="orion_asset_verify.", dir="/tmp"))
    print(f"[1/4] tmp project {tmpdir}")
    print('      project.godot config_version=5 features=("4.7","GL Compatibility")')

    (tmpdir / "project.godot").write_text(TMP_PROJECT_GODOT, encoding="utf-8")
    for name in GLBS:
        shutil.copy2(ASSETS / name, tmpdir / name)
    shutil.copy2(CHECK_TREE_GD, tmpdir / CHECK_TREE_GD.name)
    shutil.copy2(CHECK_TREE_TSCN, tmpdir / CHECK_TREE_TSCN.name)
    print(f"      copied: {', '.join(GLBS)}, {CHECK_TREE_GD.name}, {CHECK_TREE_TSCN.name}")

    ok = True
    proc = run([GODOT, "--headless", "--path", str(tmpdir), "--import"], timeout=300)
    if proc.returncode != 0:
        problem(f"临时工程 --import rc={proc.returncode}")
        dump_output(proc)
        ok = False
    else:
        print("      godot --headless --path … --import            rc=0")

    for name in GLBS:
        import_file = tmpdir / (name + ".import")
        if not import_file.is_file() or import_file.stat().st_size == 0:
            problem(f"临时工程缺 {name}.import")
            ok = False
            continue
        dest = ""
        for line in import_file.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith("dest_files=") or "res://.godot/imported/" in line:
                dest = line.strip()
                break
        print(f"      {name}.import  OK  {dest}")

    imported = tmpdir / ".godot" / "imported"
    scn = sorted(imported.glob("*.scn")) if imported.is_dir() else []
    md5 = sorted(imported.glob("*.md5")) if imported.is_dir() else []
    if len(scn) != 2:
        problem(f".godot/imported/*.scn 数量={len(scn)}（期望 2）：{[p.name for p in scn]}")
        ok = False
    for name in GLBS:
        prefix = name + "-"
        if not any(p.name.startswith(prefix) and p.suffix == ".scn" for p in scn):
            problem(f".godot/imported 里没有 {prefix}*.scn")
            ok = False
        if not any(p.name.startswith(prefix) and p.suffix == ".md5" for p in md5):
            problem(f".godot/imported 里没有 {prefix}*.md5")
            ok = False
    print(f"      .godot/imported/ *.scn={len(scn)}  *.md5={len(md5)}")

    proc = run([GODOT, "--headless", "--path", str(tmpdir), "res://check_tree.tscn"], timeout=90)
    print("      --- CheckTree output ---")
    for line in (proc.stdout or "").rstrip().splitlines():
        print("      | " + line)
    for line in (proc.stderr or "").rstrip().splitlines():
        print("      ! " + line)
    if proc.returncode != 0:
        problem(f"CheckTree rc={proc.returncode}（期望 0）")
        ok = False
    parse_check_tree(proc.stdout or "")

    if ok and not keep_tmp:
        shutil.rmtree(tmpdir, ignore_errors=True)
        print(f"      cleaned {tmpdir}")
    else:
        print(f"      kept tmpdir: {tmpdir}")
    return ok


# ── 段 2：真实工程 --import ───────────────────────────────────────────────────


def segment2(baseline: dict) -> bool:
    print("[2/4] real project import")
    ok = True
    proc = run([GODOT, "--headless", "--path", str(WORLD), "--import"], timeout=300)
    combined = (proc.stdout or "") + (proc.stderr or "")
    error_lines = [ln for ln in combined.splitlines() if "ERROR" in ln]
    if proc.returncode != 0:
        problem(f"真实工程 --import rc={proc.returncode}")
        dump_output(proc)
        ok = False
    if error_lines:
        for line in error_lines[:20]:
            print("      | " + line)
        problem(f"真实工程 --import 出现 {len(error_lines)} 行 ERROR")
        ok = False
    print(f"      godot --headless --path orion-simulation-world --import  rc={proc.returncode}  ERROR_lines={len(error_lines)}")

    found = [name for name in GLBS if (ASSETS / (name + ".import")).is_file()]
    print(f"      assets/*.glb.import = {len(found)}")
    if len(found) != 2:
        problem(f"assets/ 缺 .glb.import：{[n for n in GLBS if n not in found]}")
        ok = False

    # Godot 4.7 编辑器扫描会给每个 .gd 生成 .gd.uid —— 那等于往 src/ 里加文件（R2）
    src_root = WORLD / "src"
    now = tree_files(src_root) if src_root.is_dir() else {}
    added = sorted(set(now) - set(baseline["src_files"]))
    removed = sorted(set(baseline["src_files"]) - set(now))
    stray = [rel for rel in added if not rel.endswith(".gd.uid")]
    uids = [rel for rel in added if rel.endswith(".gd.uid")]
    for rel in uids:
        (src_root / rel).unlink(missing_ok=True)
    if uids:
        print(f"      cleanup: removed {len(uids)} generated src/**/*.gd.uid")
    else:
        print("      cleanup: no new src/**/*.gd.uid")

    after = tree_files(src_root) if src_root.is_dir() else {}
    after_sha = tree_digest(after)
    if stray:
        problem(f"src/ 出现非 .uid 的新文件：{stray[:10]}")
        ok = False
    if removed:
        problem(f"src/ 少了文件（本次运行导致）：{removed[:10]}")
        ok = False
    if after_sha != baseline["src_sha"]:
        problem(f"src_tree_sha 变了：{baseline['src_sha'][:8]}… → {after_sha[:8]}…")
        ok = False
    print(
        f"      src_tree_sha={after_sha[:8]}… "
        f"({'unchanged' if after_sha == baseline['src_sha'] else 'CHANGED (was ' + baseline['src_sha'][:8] + '…)'})"
    )

    for rel, want in baseline["watch"].items():
        path = WORLD / rel
        got = sha256_file(path) if path.is_file() else "<missing>"
        if got != want:
            problem(f"{rel} 被改动：sha {want[:12]}… → {got[:12]}…")
            ok = False
        else:
            print(f"      {rel} sha unchanged")
    return ok


# ── 段 3：assets/ 白名单 ──────────────────────────────────────────────────────


def segment3() -> bool:
    ok = True
    names = set(os.listdir(ASSETS))
    missing = EXPECTED_ASSETS - names
    extra = names - EXPECTED_ASSETS
    blends = sorted(n for n in names if n.endswith(".blend"))
    print(f"[3/4] assets/ whitelist  files={len(names)}  .blend={len(blends)}")
    for name in sorted(names):
        path = ASSETS / name
        print(f"      {name:36s} {path.stat().st_size:>7d} B")
    if missing:
        problem(f"assets/ 缺文件：{sorted(missing)}")
        ok = False
    if extra:
        problem(f"assets/ 多出文件：{sorted(extra)}")
        ok = False
    if blends:
        problem(f"assets/ 出现 .blend（Godot 会尝试用 Blender 导入）：{blends}")
        ok = False
    for name in GLBS:
        path = ASSETS / name
        if path.is_file() and path.stat().st_size <= 1024:
            problem(f"{name} 只有 {path.stat().st_size} B，疑似空导出")
            ok = False
        KEY_NUMBERS[f"{name}/bytes"] = str(path.stat().st_size) if path.is_file() else "<missing>"
    return ok


# ── 段 4：git status delta ───────────────────────────────────────────────────


ALLOWED_PREFIXES = ("orion-simulation-world/assets/", "Tool/models/")
FORBIDDEN_PREFIXES = (
    "orion-simulation-world/src/",
    "Task/",
    "Workbook/",
)
FORBIDDEN_EXACT = ("orion-simulation-world/project.godot", "orion-simulation-world/COMPONENTS.md")


def segment4(baseline: dict) -> bool:
    ok = True
    before = baseline["git"]
    after = git_status()
    added = sorted(after - before)
    vanished = sorted(before - after)
    print(f"[4/4] git status delta: +{len(added)} / -{len(vanished)} (baseline {len(before)} entries)")

    for line in added:
        path = line[3:].strip()
        if path.startswith('"') and path.endswith('"'):
            path = path[1:-1]
        allowed = path.startswith(ALLOWED_PREFIXES)
        if path in FORBIDDEN_EXACT or path.startswith(FORBIDDEN_PREFIXES):
            problem(f"禁改路径出现新条目：{line}")
            ok = False
            continue
        if not allowed:
            problem(f"顺带改了非白名单路径：{line}")
            ok = False
            continue
        if path.endswith(".glb") or path.endswith(".glb.import"):
            print(f"      + {line}   (assets 产物)")
        else:
            print(f"      + {line}   (Tool/models)")

    for line in vanished:
        path = line[3:].strip()
        if path.startswith(FORBIDDEN_PREFIXES) or path in FORBIDDEN_EXACT:
            problem(f"禁改路径条目消失：{line}")
            ok = False

    if not added and not vanished:
        print("      delta 为空（工作树在运行前后完全一致）")
    return ok


# ── main ─────────────────────────────────────────────────────────────────────


def main() -> int:
    global GODOT

    parser = argparse.ArgumentParser(description="Godot 4.7 资产验收（AABB / 原点 / 朝向）")
    parser.add_argument("--keep-tmp", action="store_true", help="无论成败都保留 /tmp 临时工程")
    parser.add_argument("--godot", default=None, help="godot 可执行文件路径（默认自动查找）")
    parser.add_argument("--skip-real-import", action="store_true", help="跳过段 2（只验 /tmp 导入）")
    args = parser.parse_args()

    GODOT = args.godot or shutil.which("godot") or "/usr/local/bin/godot"
    if not Path(GODOT).exists():
        print(f"[FATAL] 找不到 godot（{GODOT}）")
        return 2
    version = subprocess.run([GODOT, "--version"], capture_output=True, text=True)
    print(f"godot: {GODOT}  {version.stdout.strip()}")
    print(f"root : {PROJECT_ROOT}")
    print()

    for path in (CHECK_TREE_GD, CHECK_TREE_TSCN):
        if not path.is_file():
            print(f"[FATAL] 缺 {path}")
            return 2
    for name in GLBS:
        if not (ASSETS / name).is_file():
            print(f"[FATAL] 缺 {ASSETS / name}")
            return 2

    baseline = segment0()
    print()

    results = []
    try:
        results.append(("1 tmp import + CheckTree", segment1(args.keep_tmp)))
        print()
        if args.skip_real_import:
            print("[2/4] skipped (--skip-real-import)")
        else:
            results.append(("2 real project import", segment2(baseline)))
        print()
        results.append(("3 assets whitelist", segment3()))
        print()
        results.append(("4 git status delta", segment4(baseline)))
    except KeyboardInterrupt:
        print("\n[FATAL] interrupted")
        return 1

    print()
    print("=" * 78)
    for name, info in sorted(KEY_NUMBERS.items()):
        print(f"  {name:34s} {info}")
    print("-" * 78)
    for name, ok in results:
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}")
    print("-" * 78)
    print("  [SPEC] ugv full X: step.md=0.30 body-only=0.30 -> full=0.42 "
          "(= wheel_base 0.30 + 2*WHEEL_RADIUS 0.06, DiffDrive.gd:41,33,159)")
    print("=" * 78)

    passed = sum(1 for _, ok in results if ok)
    if passed == len(results) and not PROBLEMS:
        print(f"RESULT: ALL PASS ({passed}/{len(results)})")
        return 0
    print(f"RESULT: FAIL ({passed}/{len(results)})")
    for message in PROBLEMS:
        print(f"  - {message}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
